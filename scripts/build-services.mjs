/**
 * Generates services/<slug>.html — one page per service, showing what's
 * included plus real past work for that service pulled from content/projects.json.
 */
import { readFileSync, writeFileSync, mkdirSync, readdirSync, rmSync, existsSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const services = JSON.parse(readFileSync(resolve(root, 'content/services.json'), 'utf-8'));
const projects = JSON.parse(readFileSync(resolve(root, 'content/projects.json'), 'utf-8'));
const site = JSON.parse(readFileSync(resolve(root, 'content/site.json'), 'utf-8'));

const esc = (s = '') =>
  String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');

function assetFiles(folder, exts) {
  if (!folder) return [];
  const dir = resolve(root, 'public/assets', folder);
  if (!existsSync(dir)) return [];
  return readdirSync(dir).filter((f) => exts.test(f)).sort().map((f) => `/assets/${folder}/${f}`);
}
const imgs = (f) => assetFiles(f, /\.(jpe?g|png|webp)$/i);
const vids = (f) => assetFiles(f, /\.mp4$/i);

const outDir = resolve(root, 'services');
mkdirSync(outDir, { recursive: true });
for (const f of readdirSync(outDir)) if (f.endsWith('.html')) rmSync(resolve(outDir, f));

/** collect up to `max` visual tiles for a service across all projects */
function workTiles(slug, max = 12) {
  const tiles = [];
  for (const p of projects) {
    for (const item of p.showcase || []) {
      if (!(item.services || []).includes(slug)) continue;
      const isVid = item.mode === 'gallery-video' || (item.mode === 'video-embed' && !item.items);
      let files = [];
      if (item.folder) files = isVid ? vids(item.folder) : imgs(item.folder);
      if (item.src) files = [item.src];
      for (const src of files) {
        tiles.push({ src, project: p.name, slug: p.slug, label: item.label, video: /\.mp4$/i.test(src) });
      }
      // embeds (youtube/ig) — link out via the case study instead of tiling
    }
  }
  return tiles.slice(0, max);
}

function pageHTML(svc, prev, next) {
  const title = `${esc(svc.name)} — ${esc(site.name)}`;
  const path = `/services/${svc.slug}.html`;
  const tiles = workTiles(svc.slug);
  const usedBy = projects.filter((p) => (p.showcase || []).some((i) => (i.services || []).includes(svc.slug)));

  const tileHTML = tiles.length
    ? `<div class="sc-gallery svc-work__grid" data-reveal-group>
      ${tiles
        .map(
          (t) => `<a class="tile" href="/portfolio/${t.slug}.html" data-reveal-child data-cursor="Open" title="${esc(t.project)} — ${esc(t.label)}">
          ${t.video ? `<video muted loop playsinline preload="metadata" data-loop-tile src="${esc(t.src)}#t=0.1"></video>` : `<img loading="lazy" src="${esc(t.src)}" alt="${esc(t.project)} — ${esc(t.label)}" />`}
          <span class="tile__cap">${esc(t.project)}</span>
        </a>`,
        )
        .join('')}
    </div>`
    : `<p class="sc-note" data-reveal>Work samples coming soon.</p>`;

  return `<!-- AUTO-GENERATED by scripts/build-services.mjs — edit content/services.json -->
<head>
{{> head title="${title}" description="${esc(svc.long)}" path="${path}" }}
</head>

{{> lamp }}
{{> header }}

<main id="main" data-theme="${esc(svc.color)}">
  <section class="svc-hero">
    <div class="glow-blue" style="width:46rem;height:46rem;left:-12rem;top:-14rem"></div>
    <div class="container-x">
      <a class="cs-back link-u" href="/services.html" data-cursor="Back">&larr; All services</a>
      <p class="label" data-reveal>Service</p>
      <h1 class="text-display" data-reveal>${esc(svc.name)}</h1>
      <p class="svc-hero__line text-lead" data-reveal>${esc(svc.long)}</p>
      <a class="btn" href="tel:{{site.contact.phoneDial}}" data-magnetic data-reveal data-cursor="Call">Call now</a>
    </div>
  </section>

  <section class="section svc-detail">
    <div class="container-x svc-detail__grid">
      <div data-reveal>
        <p class="label">What's included</p>
        <ul class="svc-detail__list">${svc.points.map((x) => `<li>${esc(x)}</li>`).join('')}</ul>
      </div>
      <div data-reveal>
        <p class="label">How we approach it</p>
        <ol class="svc-detail__steps">${svc.approach.map((x) => `<li>${esc(x)}</li>`).join('')}</ol>
      </div>
    </div>
  </section>

  <section class="section svc-work">
    <div class="container-x">
      <div class="sec-head" data-reveal>
        <p class="label">Selected work</p>
        <h2 class="text-h2">${esc(svc.name)} in the wild.</h2>
      </div>
      ${tileHTML}
      ${usedBy.length ? `<p class="svc-work__used" data-reveal>Delivered for ${usedBy.map((p) => `<a class="link-u" href="/portfolio/${p.slug}.html">${esc(p.name)}</a>`).join(', ')}.</p>` : ''}
    </div>
  </section>

  <nav class="cs-next">
    <div class="container-x cs-next__pair">
      <a class="cs-next__link" href="/services/${prev.slug}.html" data-cursor="Open">&larr; ${esc(prev.name)}</a>
      <a class="cs-next__link cs-next__link--end" href="/services/${next.slug}.html" data-cursor="Open">${esc(next.name)} &rarr;</a>
    </div>
  </nav>

  {{> cta heading="Need ${esc(svc.name.toLowerCase())}?" callNow=true cta="Call now" }}
</main>

{{> footer }}
`;
}

services.forEach((s, i) => {
  const prev = services[(i - 1 + services.length) % services.length];
  const next = services[(i + 1) % services.length];
  writeFileSync(resolve(outDir, `${s.slug}.html`), pageHTML(s, prev, next), 'utf-8');
});

console.log(`build-services: wrote ${services.length} service page(s) to services/`);
